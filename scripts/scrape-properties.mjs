import { rename, writeFile } from 'node:fs/promises';
import { parseProperties } from './parse-properties.mjs';

const SOURCE = 'https://www.inmobiliariamakale.com.co/inmuebles/';
const OUTPUT = new URL('../src/data/properties.js', import.meta.url);
const TEMP = new URL('../src/data/properties.js.tmp', import.meta.url);

const response = await fetch(SOURCE, {
  headers: { 'user-agent': 'Mozilla/5.0 (compatible; MakaleSite/1.0)' }
});

if (!response.ok) {
  throw new Error(`No se pudo leer ${SOURCE}: HTTP ${response.status}`);
}

const properties = parseProperties(await response.text());

if (properties.length === 0) {
  throw new Error('El listado no devolvió inmuebles completos; se conserva la copia anterior.');
}

const content = `// Generated by scripts/scrape-properties.mjs — do not edit.

export const propertyTypes = ['Comprar', 'Arrendar'];

export const properties = ${JSON.stringify(properties, null, 2)};
`;

await writeFile(TEMP, content);
await rename(TEMP, OUTPUT);

console.log(`${properties.length} inmuebles actualizados en src/data/properties.js`);
